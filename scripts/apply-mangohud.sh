#!/bin/sh
# Применить настройки MangoHud из prefs.json в конфиг ~/.config/MangoHud/MangoHud.conf
set -e

CONF="$HOME/.config/MangoHud/MangoHud.conf"
mkdir -p "$(dirname "$CONF")"

# Читаем значения из prefs.json
ENABLED=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudEnabled', False)).lower())")
FPS=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudFPS', True)).lower())")
CPU=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudCPU', True)).lower())")
GPU=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudGPU', True)).lower())")
RAM=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudRAM', True)).lower())")
VRAM=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudVRAM', False)).lower())")
FRAMETIME=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudFrameTime', True)).lower())")
VERSION=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudVersion', False)).lower())")
ENGINE=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudEngine', False)).lower())")
IO=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudIO', False)).lower())")
MEDIA=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(str(d.get('mangohudMedia', False)).lower())")
ALPHA=$(python3 -c "import json; d=json.load(open('$HOME/oberon/prefs.json')); print(d.get('mangohudHudAlpha', 1.0))")

# Записываем конфиг
cat > "$CONF" << EOF
# MangoHud configuration — auto-generated by Oberon
# Edit via Oberon Settings → Games

fps=$FPS
cpu=$CPU
gpu=$GPU
ram=$RAM
vram=$VRAM
frametime=$FRAMETIME
version=$VERSION
engine=$ENGINE
io=$IO
media=$MEDIA
alpha=$ALPHA
EOF

# Если MangoHud выключен, добавляем no_display
if [ "$ENABLED" = "false" ]; then
    echo "no_display=true" >> "$CONF"
fi

echo "MangoHud config applied: $CONF"
